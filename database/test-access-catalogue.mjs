import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pages} from '../fabric-poc/src/fabric/catalog.js';
const catalogue=JSON.parse(readFileSync(new URL('./catalogue/screen-table-map.json',import.meta.url),'utf8'));
const {resources,mappings}=catalogue;
assert.equal(new Set(resources.map(r=>r.key)).size,resources.length,'Resource keys must be unique');
assert.equal(new Set(mappings.map(m=>[m.resource_key,m.schema_name,m.table_name].join('|'))).size,mappings.length,'Resource/table pairs must be unique');
for(const key of Object.keys(pages))assert.ok(resources.some(r=>r.key===key),`Missing resource: ${key}`);
assert.ok(mappings.every(m=>!m.can_delete),'Deletion is not enabled in this pilot');
assert.ok(mappings.filter(m=>['lookup','report_source'].includes(m.relation_type)).every(m=>!m.can_create&&!m.can_edit),'Lookups and reports must not write');
assert.ok(resources.filter(r=>r.parent==='section:admin').every(r=>r.admin_only),'Administration is protected');
assert.equal(resources.find(r=>r.key==='materialContacts').parent,'section:miscellaneous');
for(const key of ['yarnTypes','fabricTypes'])assert.equal(resources.find(r=>r.key===key).parent,'section:fabric');
assert.equal(resources.find(r=>r.key==='brands').parent,'section:production');
assert.ok(!resources.some(r=>r.key==='section:reference'));
assert.ok(!mappings.some(m=>m.resource_key==='materialContacts'&&m.table_name==='contact_bank_account'),'Contact view must not read banking data');
assert.ok(!mappings.some(m=>m.schema_name==='auth'),'Auth identities are handled by protected commands');
for(const table_name of ['knitting_bill','knitting_bill_item'])assert.ok(mappings.some(m=>m.resource_key==='knitting'&&m.table_name===table_name&&m.can_edit));
assert.ok(mappings.some(m=>m.resource_key==='knitting'&&m.table_name==='yarn_bill_item'&&!m.can_edit));
console.log(`Catalogue checks passed: ${resources.length} resources, ${mappings.length} mappings`);
