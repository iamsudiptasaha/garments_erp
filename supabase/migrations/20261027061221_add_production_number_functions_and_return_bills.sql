CREATE FUNCTION garments_erp.generate_job_code(p_stage_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE v_abbr text; v_year integer; v_fy text; v_number bigint;
BEGIN
 SELECT s.abbr INTO v_abbr FROM garments_erp.stage s WHERE s.id=p_stage_id FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Stage % does not exist', p_stage_id; END IF;
 IF v_abbr IS NULL OR btrim(v_abbr)='' THEN RAISE EXCEPTION 'Stage abbreviation is required'; END IF;
 v_year := extract(year from CURRENT_DATE)::integer - CASE WHEN extract(month from CURRENT_DATE)<4 THEN 1 ELSE 0 END;
 v_fy := right(v_year::text,2)||'-'||right((v_year+1)::text,2);
 INSERT INTO garments_erp.document_number_counter AS c(document_type,financial_year,last_number)
 VALUES ('JOB:'||v_abbr,v_fy,1)
 ON CONFLICT(document_type,financial_year) DO UPDATE SET last_number=c.last_number+1
 RETURNING last_number INTO v_number;
 IF v_number > 99999 THEN RAISE EXCEPTION 'Job counter capacity exceeded for stage % in %',v_abbr,v_fy; END IF;
 RETURN v_abbr||'/'||lpad(v_number::text,5,'0')||'/'||v_fy;
END;
$function$;
CREATE FUNCTION garments_erp.generate_challan_number()
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE v_year integer; v_fy text; v_number bigint;
BEGIN
 v_year := extract(year from CURRENT_DATE)::integer - CASE WHEN extract(month from CURRENT_DATE)<4 THEN 1 ELSE 0 END;
 v_fy := right(v_year::text,2)||'-'||right((v_year+1)::text,2);
 INSERT INTO garments_erp.document_number_counter AS c(document_type,financial_year,last_number)
 VALUES ('SCC',v_fy,1)
 ON CONFLICT(document_type,financial_year) DO UPDATE SET last_number=c.last_number+1
 RETURNING last_number INTO v_number;
 IF v_number > 9999 THEN RAISE EXCEPTION 'Challan counter capacity exceeded in %',v_fy; END IF;
 RETURN 'SCC/'||lpad(v_number::text,4,'0')||'/'||v_fy;
END;
$function$;
REVOKE EXECUTE ON FUNCTION garments_erp.generate_job_code(bigint), garments_erp.generate_challan_number() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION garments_erp.generate_job_code(bigint), garments_erp.generate_challan_number() TO authenticated, service_role;
COMMENT ON FUNCTION garments_erp.generate_job_code(bigint) IS 'Call explicitly when creating a job; save returned text in job.job_code. Per-stage abbreviation and April-March financial year counter. No insert trigger.';
COMMENT ON FUNCTION garments_erp.generate_challan_number() IS 'Call explicitly when generating a challan; save returned text in challan.challan_number. April-March financial year from CURRENT_DATE, independent of issue_date. No insert trigger.';
