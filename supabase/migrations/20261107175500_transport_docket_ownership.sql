begin;

-- Introduce transport-level docket ownership before changing carton assignments.
lock table garments_erp.transport_item, garments_erp.transport_docket in access exclusive mode;

create table garments_erp.transport_status_type (
  id bigint generated always as identity primary key,
  type text not null unique
);

insert into garments_erp.transport_status_type (type) values ('draft'), ('dispatched');

create table garments_erp.transport (
  id bigint generated by default as identity primary key,
  appointment_date date,
  transporter_id bigint not null references garments_erp.transporter(id),
  asn_confirmed boolean,
  asn_master text,
  e_way_bill_number text,
  warehouse_in_date date,
  transport_status_type_id bigint not null references garments_erp.transport_status_type(id),
  dispatched_at timestamptz
);

alter table garments_erp.transport enable row level security;
alter table garments_erp.transport_status_type enable row level security;
revoke all on garments_erp.transport, garments_erp.transport_status_type from public, anon, authenticated;
grant select, insert, update, delete on garments_erp.transport to service_role;
grant select on garments_erp.transport_status_type to service_role;
grant usage on sequence garments_erp.transport_id_seq to service_role;

alter table garments_erp.transport_item add column transport_id bigint;
alter table garments_erp.transport_docket add column transport_id bigint;

-- Each legacy transport item held the transport header fields. Preserve that
-- identity and its metadata without inferring a shipment or grouping records.
insert into garments_erp.transport (
  id, appointment_date, transporter_id, asn_confirmed, asn_master,
  e_way_bill_number, warehouse_in_date, transport_status_type_id
)
select i.id, i.appointment_date, i.transporter_id, i.asn_confirmed, i.asn_master,
       i.e_way_bill_number, i.warehouse_in_date, s.id
from garments_erp.transport_item i
cross join garments_erp.transport_status_type s
where s.type = 'draft';

select setval(
  pg_get_serial_sequence('garments_erp.transport', 'id'),
  greatest(coalesce(max(id), 1), 1),
  coalesce(max(id) >= 1, false)
)
from garments_erp.transport;

update garments_erp.transport_item set transport_id = id;

update garments_erp.transport_docket d
set transport_id = i.transport_id
from garments_erp.transport_item i
where i.docket_number = d.docket_number;

alter table garments_erp.transport_item
  alter column transport_id set not null,
  add constraint transport_item_transport_id_fkey
    foreign key (transport_id) references garments_erp.transport(id);

create index transport_item_transport_id_idx on garments_erp.transport_item (transport_id);

alter table garments_erp.transport_docket
  alter column transport_id set not null,
  drop constraint transport_docket_docket_number_fkey,
  add constraint transport_docket_transport_id_fkey
    foreign key (transport_id) references garments_erp.transport(id),
  add constraint transport_docket_transport_id_key unique (transport_id);

commit;
