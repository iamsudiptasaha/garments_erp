
CREATE TABLE garments_erp.bucket_group_id (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bucket_id text REFERENCES storage.buckets(id) ON DELETE SET NULL,
 "group" text UNIQUE,
 description text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE garments_erp.attachments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bucket_group_id bigint REFERENCES garments_erp.bucket_group_id(id) ON DELETE SET NULL,
 storage_path text,
 filename text DEFAULT (gen_random_uuid()::text),
 address text,
 mime_type text,
 file_size text,
 uploaded_by bigint REFERENCES garments_erp.employee(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE garments_erp.bucket_group_id ENABLE ROW LEVEL SECURITY;
ALTER TABLE garments_erp.attachments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON garments_erp.bucket_group_id, garments_erp.attachments FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON garments_erp.bucket_group_id, garments_erp.attachments TO service_role;
GRANT USAGE, SELECT ON SEQUENCE garments_erp.bucket_group_id_id_seq, garments_erp.attachments_id_seq TO service_role;
CREATE INDEX attachments_bucket_group_id_idx ON garments_erp.attachments(bucket_group_id);
CREATE INDEX attachments_uploaded_by_idx ON garments_erp.attachments(uploaded_by);
CREATE INDEX bucket_group_id_bucket_id_idx ON garments_erp.bucket_group_id(bucket_id);

LOCK TABLE garments_erp.item, garments_erp.buyer_po, garments_erp.employee IN ACCESS EXCLUSIVE MODE;
DO $guard$
BEGIN
 IF EXISTS(SELECT 1 FROM garments_erp.item WHERE image IS NOT NULL)
 OR EXISTS(SELECT 1 FROM garments_erp.buyer_po WHERE image IS NOT NULL)
 OR EXISTS(SELECT 1 FROM garments_erp.employee WHERE supporting_document_1_upload IS NOT NULL OR supporting_document_2_upload IS NOT NULL)
 THEN RAISE EXCEPTION 'Existing file values need explicit mapping before conversion'; END IF;
END;
$guard$;
ALTER TABLE garments_erp.item RENAME COLUMN image TO image_attachment;
ALTER TABLE garments_erp.item ALTER COLUMN image_attachment TYPE bigint USING image_attachment::bigint;
ALTER TABLE garments_erp.buyer_po RENAME COLUMN image TO po_attachment;
ALTER TABLE garments_erp.buyer_po ALTER COLUMN po_attachment TYPE bigint USING po_attachment::bigint;
ALTER TABLE garments_erp.employee RENAME COLUMN supporting_document_1 TO supporting_document_1_title;
ALTER TABLE garments_erp.employee RENAME COLUMN supporting_document_2 TO supporting_document_2_title;
ALTER TABLE garments_erp.employee
 ALTER COLUMN supporting_document_1_upload TYPE bigint USING supporting_document_1_upload::bigint,
 ALTER COLUMN supporting_document_2_upload TYPE bigint USING supporting_document_2_upload::bigint;

DO $links$
DECLARE r record;
BEGIN
 FOR r IN SELECT * FROM (VALUES
 ('yarn_bill','bill_attachment'),('knitting_bill','bill_attachment'),
 ('dyed_fabric_bill','bill_attachment'),('job_worker_bill','bill_attachment'),
 ('item','image_attachment'),('buyer_po','po_attachment'),
 ('transport_bill','bill_attachment'),('transport_docket','docket_attachment'),
 ('return_bill','bill_attachment'),('raw_material_check_in','bill_attachment'),
 ('employee','supporting_document_1_upload'),('employee','supporting_document_2_upload')
 ) AS links(table_name,column_name)
 LOOP
  IF NOT EXISTS(SELECT 1 FROM information_schema.columns c WHERE c.table_schema='garments_erp' AND c.table_name=r.table_name AND c.column_name=r.column_name) THEN
   EXECUTE format('ALTER TABLE garments_erp.%I ADD COLUMN %I bigint',r.table_name,r.column_name);
  END IF;
  EXECUTE format('ALTER TABLE garments_erp.%I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES garments_erp.attachments(id) ON DELETE SET NULL',r.table_name,r.table_name||'_'||r.column_name||'_fkey',r.column_name);
  EXECUTE format('CREATE INDEX %I ON garments_erp.%I (%I)',r.table_name||'_'||r.column_name||'_idx',r.table_name,r.column_name);
 END LOOP;
END;
$links$;

DO $timestamps$
DECLARE r record;
BEGIN
 FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname='garments_erp' AND c.relkind IN ('r','p')
 AND NOT EXISTS(SELECT 1 FROM pg_attribute a WHERE a.attrelid=c.oid AND a.attname='created_at' AND NOT a.attisdropped)
 ORDER BY c.relname
 LOOP
  EXECUTE format('ALTER TABLE garments_erp.%I ADD COLUMN created_at timestamptz',r.relname);
  EXECUTE format('ALTER TABLE garments_erp.%I ALTER COLUMN created_at SET DEFAULT now()',r.relname);
  EXECUTE format('COMMENT ON COLUMN garments_erp.%I.created_at IS %L',r.relname,'Creation timestamp, defaults to now() for new rows. NULL for historical rows whose creation time is unknown.');
 END LOOP;
END;
$timestamps$;
