CREATE FUNCTION garments_erp.generate_raw_material_po_number()
RETURNS text LANGUAGE plpgsql SECURITY INVOKER SET search_path=''
AS $fn$
DECLARE y integer; fy text; n bigint;
BEGIN
 y:=extract(year from CURRENT_DATE)::integer-CASE WHEN extract(month from CURRENT_DATE)<4 THEN 1 ELSE 0 END;
 fy:=right(y::text,2)||'-'||right((y+1)::text,2);
 INSERT INTO garments_erp.document_number_counter AS c(document_type,financial_year,last_number)
 VALUES('SCPO',fy,1)
 ON CONFLICT(document_type,financial_year) DO UPDATE SET last_number=c.last_number+1
 RETURNING last_number INTO n;
 IF n>9999 THEN RAISE EXCEPTION 'Raw material PO capacity exceeded for %',fy; END IF;
 RETURN 'SCPO/'||lpad(n::text,4,'0')||'/'||fy;
END;
$fn$;
REVOKE EXECUTE ON FUNCTION garments_erp.generate_raw_material_po_number() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION garments_erp.generate_raw_material_po_number() TO authenticated,service_role;
COMMENT ON FUNCTION garments_erp.generate_raw_material_po_number() IS 'Call explicitly and save the returned number on raw material PO creation. April-March financial year from CURRENT_DATE.';

